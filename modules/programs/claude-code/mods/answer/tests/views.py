#!/usr/bin/env python3
"""Writes views.ts: what `agent-hub answer` prints along each path the mod's tests walk. Their
sandbox can't run a process, so they replay this, and `--check` fails the mod's build when it no
longer matches agent-hub. Run with PYTHONPATH set to `pkgs/agent-hub`."""

import json
import sys
from pathlib import Path

from agent_hub import forms

GRILLING = """The bar and the funnel are independent, so this round asks both.

**Q1. Should every focus default to the same bar?**

- **A.** Yes, one default for every kind.
- **B.** Default by kind.
- **C.** Add the bar as a second pick.

> **Recommended:** A. A per-kind table is one more thing to keep in sync.

---

**Q2. Lower the per-generator target to 5–6?**

> **Recommended:** Yes. Four generators still give 20–24.

---

**Q3. What should happen to `--quick`?**

- **A.** Drop it.
- **B.** Keep it as an alias.
  Scripts may still call it."""

LONG = "**Q1. Keep the journal?**\n\n" + "\n".join(f"Line {n} of what it hangs on." for n in range(1, 13)) + """

- **A.** Keep it.
- **B.** Drop it."""

MINE = """2 findings from 4 runs, saved to `~/notes/FINDINGS.md`

1. The default bar cuts the ideas you act on · 2/3 · S · build
2. The funnel is wide and slow for what survives · 3/3 · M · /grill-me

**Top pick: 1.** Make "worth doing" the default bar."""

PLAIN = """Done. What changed:

1. The parser takes `Q` labels and numbers.
2. The review screen fills the prompt.

Tests pass."""


def pick(entry):
    return {"do": "pick", "entry": entry}


def toggle(entry):
    return {"do": "toggle", "entry": entry}


def go(step):
    return {"do": "go", "step": step}


def note(text):
    return {"do": "note", "text": text}


def write(text):
    return {"do": "write", "text": text}


REVIEW = {"do": "review"}

NEXT = {"do": "next"}

PATHS = (
    (GRILLING, pick(1), note("but keep the flag"), NEXT, pick(0), note(""), NEXT, write("drop it")),
    (GRILLING, {"do": "skip"}, go(0), go(1), pick(0), note(""), NEXT),
    # By the mouse alone: a write-in and notes typed but never entered, then the buttons.
    (GRILLING, go(2), write("drop it"), go(3), go(0), pick(0), note("for now"), go(1), REVIEW, note("thanks")),
    (GRILLING, toggle(0), toggle(2), go(1), REVIEW),
    (GRILLING, pick(1), REVIEW),
    (GRILLING, {"do": "accept"}, note(""), NEXT, go(2)),
    (MINE, pick(0), note(""), NEXT, pick(1), note(""), NEXT),
    (LONG,),
    (PLAIN,),
)


def key(path):
    """As JSON.stringify writes it, which is how the tests look a path up."""
    return json.dumps(path, ensure_ascii=False, separators=(",", ":"))


def views():
    table = {}
    for text, *actions in PATHS:
        form = forms.parse(text)
        draft = forms.new_draft(form) if form else None
        table[key([text])] = forms.view(form, draft) if form else None
        for i, action in enumerate(actions):
            draft = forms.apply(form, draft, action)
            table[key([text, *actions[:i + 1]])] = forms.view(form, draft)
    return table


def source():
    return (
        "// Generated by views.py; `--check` in the mod's build holds it to agent-hub.\n"
        f"export const GRILLING = {json.dumps(GRILLING, ensure_ascii=False)};\n"
        f"export const LONG = {json.dumps(LONG, ensure_ascii=False)};\n"
        f"export const MINE = {json.dumps(MINE, ensure_ascii=False)};\n"
        f"export const PLAIN = {json.dumps(PLAIN, ensure_ascii=False)};\n"
        f"export const VIEWS: Record<string, unknown> = {json.dumps(views(), ensure_ascii=False)};\n"
    )


if __name__ == "__main__":
    target = Path(__file__).with_name("views.ts")
    if sys.argv[1:] == ["--check"]:
        if target.read_text() != source():
            sys.exit("views.ts no longer matches agent-hub: run views.py")
    else:
        target.write_text(source())
